#!/usr/bin/env node
/**
 * Regenerates lib/airports-data.ts from the OurAirports dataset.
 *
 *   git clone --depth 1 https://github.com/davidmegginson/ourairports-data
 *   node scripts/build-airports.mjs ourairports-data/airports.csv
 *
 * OurAirports is public domain (https://ourairports.com/data/), community
 * maintained and updated near-daily. Regenerate occasionally rather than
 * hand-editing lib/airports-data.ts — codes DO change: Palm Beach went from
 * PBI to DJT on 2026-08-18, which the old hand-picked list never learned.
 *
 * Filter: large_airport + medium_airport, scheduled_service = yes, and a
 * well-formed 3-letter IATA code. 3,244 airports at the 2026-09-22 snapshot
 * (~56 KB gzipped without keywords). Large-only was considered and rejected
 * (2026-09-23): it drops Fairbanks, Juneau, Ketchikan, Sitka, Nome, Bethel,
 * Paine Field, Bellingham and Bozeman — Alaska's own network is mostly
 * "medium" in this dataset.
 *
 * No npm dependencies on purpose: a tiny RFC 4180 parser below is enough,
 * and keeps this runnable anywhere Node is.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { execSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Hand-maintained search aliases, matched at the same rank as the city
 * name. Deliberately SHORT: each entry exists because a search that worked
 * on the old hand-picked list stopped working on this dataset — measured
 * on 2026-09-23 by searching every old entry's city against the new data,
 * not guessed. OurAirports records the municipality the airport sits in
 * (Kahului, Tocumen, Taoyuan, Charlotte Amalie), not the name travellers
 * search for. Add to this only when a real search misses.
 */
const ALIASES = {
  OGG: ['Maui'],
  KOA: ['Kona', 'Big Island'],
  ITO: ['Big Island'],
  LIH: ['Kauai'],
  ZIH: ['Zihuatanejo'],
  STT: ['St. Thomas', 'Saint Thomas'],
  PTY: ['Panama City'],
  TPE: ['Taipei'],
}

function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let inQuotes = false
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"'
          i++
        } else inQuotes = false
      } else field += ch
    } else if (ch === '"') inQuotes = true
    else if (ch === ',') {
      row.push(field)
      field = ''
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++
      row.push(field)
      rows.push(row)
      row = []
      field = ''
    } else field += ch
  }
  if (field !== '' || row.length) {
    row.push(field)
    rows.push(row)
  }
  return rows
}

const csvPath = process.argv[2]
if (!csvPath) {
  console.error('usage: node scripts/build-airports.mjs <path/to/airports.csv>')
  process.exit(1)
}

const [header, ...records] = parseCsv(readFileSync(csvPath, 'utf8'))
const col = (name) => {
  const i = header.indexOf(name)
  if (i < 0) throw new Error(`airports.csv has no "${name}" column — format changed?`)
  return i
}
const C = {
  type: col('type'),
  name: col('name'),
  country: col('iso_country'),
  municipality: col('municipality'),
  scheduled: col('scheduled_service'),
  iata: col('iata_code'),
  keywords: col('keywords'),
}

const rows = records
  .filter((r) => r.length === header.length)
  .filter((r) => r[C.type] === 'large_airport' || r[C.type] === 'medium_airport')
  .filter((r) => r[C.scheduled] === 'yes')
  .filter((r) => /^[A-Z]{3}$/.test(r[C.iata]))
  .map((r) => [
    r[C.iata],
    r[C.municipality] || r[C.name],
    r[C.country],
    r[C.name],
    r[C.type] === 'large_airport' ? 1 : 0,
    (ALIASES[r[C.iata]] ?? []).join('|'),
    r[C.keywords],
  ])
  .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))

const codes = new Set(rows.map((r) => r[0]))
if (codes.size !== rows.length) throw new Error('duplicate IATA codes in filtered set')
for (const code of Object.keys(ALIASES)) {
  if (!codes.has(code)) throw new Error(`alias for ${code}, which is not in the filtered set`)
}

let source = 'unknown revision'
try {
  source = execSync('git log -1 --format="%h (%cs)"', {
    cwd: path.dirname(path.resolve(csvPath)),
  })
    .toString()
    .trim()
} catch {
  // Not a git checkout — fine, the header just says so.
}

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, '..', 'lib', 'airports-data.ts')
writeFileSync(
  out,
  `// GENERATED by scripts/build-airports.mjs — do not edit by hand.
// Source: OurAirports (public domain), ourairports-data ${source}.
// ${rows.length} large/medium airports with scheduled service.
// Columns: [iata, city, country, name, isLarge, aliases ('|'-separated), keywords]

export type AirportRow = readonly [string, string, string, string, 0 | 1, string, string]

export const AIRPORT_ROWS: readonly AirportRow[] = ${JSON.stringify(rows)}
`
)
console.log(`wrote ${rows.length} airports to ${path.relative(process.cwd(), out)} (source ${source})`)
